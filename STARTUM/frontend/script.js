function applyTheme(theme) {
  const next = theme === "dark" ? "dark" : "light";
  document.documentElement.dataset.theme = next;
  document.documentElement.style.colorScheme = next;
  const heroThemeImage = $("#heroThemeImage");
  if (heroThemeImage) {
    const heroSource =
      next === "light"
        ? "assets/images/startum-day-hero.webp"
        : "assets/images/startum-dark-hero.webp";
    if (heroThemeImage.getAttribute("src") !== heroSource)
      heroThemeImage.src = heroSource;
  }
  try {
    localStorage.setItem("startumTheme", next);
  } catch (_storageError) {}
  const metaTheme = document.querySelector('meta[name="theme-color"]');
  if (metaTheme) metaTheme.content = next === "light" ? "#F2F7F3" : "#123B46";
  applyI18n();
}

