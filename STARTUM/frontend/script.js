function setupTopbar() {
  const menu = $("#menuBtn"),
    nav = $("#mainNav");
  menu.addEventListener("click", () => {
    const open = nav.classList.toggle("mobile-open");
    document.body.classList.toggle("menu-open", open);
    menu.setAttribute("aria-expanded", String(open));
    menu.setAttribute(
      "aria-label",
      t(open ? "header.menuClose" : "header.menuOpen"),
    );
    if (open) nav.querySelector("a")?.focus();
  });
  $$(".main-nav a").forEach((a) =>
    a.addEventListener("click", () => {
      nav.classList.remove("mobile-open");
      document.body.classList.remove("menu-open");
      menu.setAttribute("aria-expanded", "false");
      menu.setAttribute("aria-label", t("header.menuOpen"));
    }),
  );
  document.addEventListener("click", (e) => {
    if (
      nav.classList.contains("mobile-open") &&
      !nav.contains(e.target) &&
      !menu.contains(e.target)
    ) {
      nav.classList.remove("mobile-open");
      document.body.classList.remove("menu-open");
      menu.setAttribute("aria-expanded", "false");
      menu.setAttribute("aria-label", t("header.menuOpen"));
    }
  });
  window.addEventListener(
    "scroll",
    () => {
      const max = document.documentElement.scrollHeight - innerHeight;
      $("#pageProgress").style.width = (max ? (scrollY / max) * 100 : 0) + "%";
      $("#topbar").style.boxShadow =
        scrollY > 8 ? "0 14px 34px rgba(0,0,0,.18)" : "";
    },
    { passive: true },
  );
  if ("IntersectionObserver" in window) {
    const links = $$(".main-nav a"),
      sections = links
        .map((a) => a.getAttribute("href"))
        .filter((href) => href && href.startsWith("#") && href.length > 1)
        .map((href) => document.querySelector(href))
        .filter(Boolean);
    const io = new IntersectionObserver(
      (entries) =>
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            links.forEach((a) => a.removeAttribute("aria-current"));
            const link = links.find(
              (a) => a.getAttribute("href") === `#${entry.target.id}`,
            );
            link?.setAttribute("aria-current", "page");
          }
        }),
      { rootMargin: "-38% 0px -52% 0px", threshold: 0 },
    );
    sections.forEach((sec) => io.observe(sec));
  }
  if (
    matchMedia("(pointer:fine) and (prefers-reduced-motion: no-preference)")
      .matches
  ) {
    $$(".magnetic").forEach((el) => {
      el.addEventListener("pointermove", (e) => {
        const r = el.getBoundingClientRect();
        el.style.transform = `translate(${(e.clientX - r.left - r.width / 2) * 0.04}px,${(e.clientY - r.top - r.height / 2) * 0.04}px)`;
      });
      el.addEventListener("pointerleave", () => (el.style.transform = ""));
    });
  }
}

