function applyCatalogFilters() {
  const input = $("#subjectSearch");
  const scopeSelect = $("#globalSearchKind");
  const sortSelect = $("#globalSearchSort");
  const query = normalizeCatalogText(input?.value || "");
  const scope = ["all", "subjects", "courses"].includes(scopeSelect?.value)
    ? scopeSelect.value
    : "all";
  const category = $(".filter.active")?.dataset.filter || "all";
  $$(".filter").forEach((button) => button.setAttribute("aria-pressed", String(button.dataset.filter === category)));
  const sort = ["relevance", "az", "newest"].includes(sortSelect?.value)
    ? sortSelect.value
    : "relevance";
  const subjectCards = $$("#subjectsGrid .subject-card");
  const specialCards = $$("#specialGrid .special-card");
  const allCards = [...subjectCards, ...specialCards];
  const hasDates = allCards.some((card) => Number.isFinite(Date.parse(card.dataset.createdAt || "")));
  const newestOption = sortSelect?.querySelector('option[value="newest"]');
  if (newestOption) {
    newestOption.disabled = !hasDates;
    if (!hasDates && sortSelect.value === "newest") sortSelect.value = "relevance";
  }
  const activeSort = hasDates ? sort : (sort === "newest" ? "relevance" : sort);
  const collator = new Intl.Collator(lang === "ru" ? "ru" : lang === "en" ? "en" : "uz", {
    sensitivity: "base",
    numeric: true,
  });
  let visibleSubjects = 0;
  let visibleSpecials = 0;
  const filterGroup = (cards, kind) => {
    const ordered = [...cards].sort((left, right) => {
      if (activeSort === "az") return collator.compare(left.dataset.sortName || "", right.dataset.sortName || "");
      if (activeSort === "newest") {
        const dateDiff = Date.parse(right.dataset.createdAt || "") - Date.parse(left.dataset.createdAt || "");
        if (Number.isFinite(dateDiff) && dateDiff !== 0) return dateDiff;
      }
      return Number(left.dataset.order || 0) - Number(right.dataset.order || 0);
    });
    let visibleIndex = 0;
    ordered.forEach((card, index) => {
      const typeMatches = scope === "all" || (scope === "subjects" && kind === "subject") || (scope === "courses" && kind === "special");
      const categoryMatches = category === "all" || card.dataset.category === category;
      const queryMatches = !query || normalizeCatalogText(card.dataset.search || "").includes(query);
      const visible = typeMatches && categoryMatches && queryMatches;
      card.hidden = !visible;
      card.classList.toggle("hidden", !visible);
      const number = card.querySelector(kind === "subject" ? ".subject-index" : ".special-number");
      if (visible) {
        visibleIndex++;
        if (number) number.textContent = String(visibleIndex).padStart(2, "0");
      } else if (number) {
        number.textContent = String(index + 1).padStart(2, "0");
      }
      if (visible && kind === "subject") visibleSubjects++;
      if (visible && kind === "special") visibleSpecials++;
      card.parentElement?.append(card);
    });
  };
  filterGroup(subjectCards, "subject");
  filterGroup(specialCards, "special");
  const subjectsGrid = $("#subjectsGrid");
  const specialSection = $("#special");
  const empty = $("#subjectEmpty");
  if (subjectsGrid) subjectsGrid.hidden = visibleSubjects === 0;
  if (specialSection) specialSection.hidden = visibleSpecials === 0;
  const totalVisible = visibleSubjects + visibleSpecials;
  if (empty) {
    empty.hidden = totalVisible > 0;
    const emptyText = empty.querySelector("p");
    if (emptyText) emptyText.textContent = query || category !== "all" || scope !== "all"
      ? t("search.emptyFiltered")
      : t("subjects.emptyText");
  }
  const status = $("#catalogStatus");
  if (status) {
    const showStatus = Boolean(query || category !== "all" || scope !== "all" || activeSort !== "relevance");
    status.hidden = !showStatus;
    status.textContent = `${totalVisible} ${t("search.count")}`;
  }
}

function observeReveal() {
  if (!("IntersectionObserver" in window)) {
    $$(".reveal").forEach((x) => x.classList.add("visible"));
    return;
  }
  if (observeReveal.io) {
    $$(".reveal").forEach((e) => {
      if (!e.classList.contains("visible")) observeReveal.io.observe(e);
    });
    return;
  }
  observeReveal.io = new IntersectionObserver(
    (entries) =>
      entries.forEach((en) => {
        if (en.isIntersecting) {
          en.target.classList.add("visible");
          observeReveal.io.unobserve(en.target);
        }
      }),
    { threshold: 0.08 },
  );
  $$(".reveal").forEach((e) => observeReveal.io.observe(e));
}

