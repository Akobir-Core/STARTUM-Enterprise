function subjectName(s) {
  if (lang === "uz") return s.uz;
  if (lang === "ru")
    return translationsBySubject.ru?.[s.uz] || s.ru || s.en || s.uz;
  return translationsBySubject.en?.[s.uz] || s.en || s.uz;
}
function descText(s) {
  return s.desc[lang] || s.desc.en;
}
function courseDisplayName(item) {
  if (!item?.uz) return item;
  if (SUBJECT_ICON[item.uz]) return subjectName(item);
  if (lang === "uz") return item.uz;
  if (lang === "ru") return item.ru || item.en || item.uz;
  return item.en || item.uz;
}

function normalizeCatalogText(value) {
  return String(value || "")
    .normalize("NFKC")
    .toLocaleLowerCase("uz")
    .replace(/[’‘ʻ`]/g, "'")
    .replace(/\s+/g, " ")
    .trim();
}

function catalogSearchText(item) {
  const categoryTerms = {
    science: ["aniq fan", "aniq fanlar", "science", "sciences", "точные науки"],
    language: ["til", "tillar", "language", "languages", "язык", "языки"],
    human: ["gumanitar", "humanities", "гуманитарные"],
    special: ["maxsus", "maxsus dastur", "dastur", "special", "program", "программа"],
  };
  const parts = [item.uz, item.ru, item.en, item.backendSlug, ...(item.keywords || []), ...(categoryTerms[item.category] || [])];
  if (item.desc && typeof item.desc === "object") parts.push(...Object.values(item.desc));
  return normalizeCatalogText(parts.filter(Boolean).join(" "));
}

function catalogCategoryLabel(category) {
  return t(`search.category.${category}`) || category;
}

function inferSubjectCategory(course) {
  const text = normalizeCatalogText([
    course.name_uz, course.name_ru, course.name_en,
    course.description_uz, course.description_ru, course.description_en,
  ].join(" "));
  if (/til|language|язык|англий|русск|корей|немец|турец/.test(text)) return "language";
  if (/matem|math|fizik|physics|kimyo|chem|biolog|biology|арифмет|наук/.test(text)) return "science";
  return "human";
}

