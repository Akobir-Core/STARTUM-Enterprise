function renderSchedule() {
  const data = schedule[lang],
    keys = Object.keys(data);
  if (!dayKey || !data[dayKey]) dayKey = keys[0];
  const dayIndex = keys.indexOf(dayKey);
  $("#dayTabs").innerHTML = keys
    .map(
      (k, i) =>
        `<button class="day-tab ${k === dayKey ? "active" : ""}" type="button" role="tab" aria-selected="${k === dayKey}" data-day="${escapeHtml(k)}">${escapeHtml(k)}</button>`,
    )
    .join("");

  // Replace outdated one-off English/German sample rows with the verified,
  // consistent language schedule. Keep all unrelated existing course rows.
  const legacyLanguageNames = new Set([
    "ingliz tili",
    "english",
    "английский язык",
    "rus tili",
    "russian",
    "русский язык",
    "koreys tili",
    "korean",
    "корейский язык",
    "nemis tili",
    "german",
    "немецкий язык",
  ]);
  const sourceRows = data[dayKey] || [];
  const actualEnglishRows = sourceRows.filter((row) =>
    ["ingliz tili", "english", "английский язык"].includes(
      String(row[1] || "")
        .trim()
        .toLocaleLowerCase(),
    ),
  );
  const existingRows = sourceRows.filter(
    (row) =>
      !legacyLanguageNames.has(
        String(row[1] || "")
          .trim()
          .toLocaleLowerCase(),
      ),
  );
  const languageRows = (dailyLanguageSchedule[lang] || []).filter((row) => {
    const isEnglish = ["ingliz tili", "english", "английский язык"].includes(
      String(row[1] || "")
        .trim()
        .toLocaleLowerCase(),
    );
    return !(dayIndex === 0 && actualEnglishRows.length && isEnglish);
  });
  // Monday has a verified English slot in the original timetable; retain it
  // instead of replacing it with the broader daily operating window.
  if (actualEnglishRows.length) languageRows.push(...actualEnglishRows);
  if ([0, 2, 4].includes(dayIndex)) languageRows.push(germanScheduleRow[lang]);
  const rows = [...existingRows, ...languageRows].sort((a, b) => {
    const minutes = (value) => {
      const match = String(value || "").match(/^(\d{2}):(\d{2})/);
      return match
        ? Number(match[1]) * 60 + Number(match[2])
        : Number.MAX_SAFE_INTEGER;
    };
    return minutes(a[0]) - minutes(b[0]);
  });

  $("#scheduleList").innerHTML = rows
    .map(
      (row) =>
        `<div class="schedule-row"><div class="schedule-time">${escapeHtml(row[0])}</div><div class="schedule-course">${escapeHtml(row[1])}</div><div class="schedule-teacher">${escapeHtml(row[2])}</div></div>`,
    )
    .join("");
  $$(".day-tab").forEach((b) =>
    b.addEventListener("click", () => {
      dayKey = b.dataset.day;
      renderSchedule();
    }),
  );
}

function formatCalendarDate(value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return String(value || "");
  return new Intl.DateTimeFormat(
    lang === "ru" ? "ru-RU" : lang === "en" ? "en-GB" : "uz-UZ",
    {
      timeZone: "Asia/Tashkent",
      dateStyle: "medium",
      timeStyle: "short",
    },
  ).format(date);
}

async function renderCalendarEvents() {
  const panel = $("#calendarEventsPanel");
  const root = $("#calendarEvents");
  if (!panel || !root) return;
  panel.hidden = false;
  root.replaceChildren();
  try {
    const response = await fetch(
      `${API_BASE_URL}/calendar?language=${encodeURIComponent(lang)}&limit=8`,
      {
        headers: { Accept: "application/json" },
        cache: "no-store",
      },
    );
    if (!response.ok) throw new Error(`calendar_${response.status}`);
    const data = await response.json();
    const items = Array.isArray(data.items) ? data.items : [];
    if (!items.length) {
      const empty = document.createElement("p");
      empty.className = "calendar-empty";
      empty.textContent = t("calendar.empty");
      root.append(empty);
      return;
    }
    for (const item of items) {
      const article = document.createElement("article");
      article.className = "calendar-event-card";
      const date = document.createElement("time");
      date.className = "calendar-event-date";
      date.dateTime = String(item.starts_at || "");
      const eventDate = new Date(item.starts_at);
      if (!Number.isNaN(eventDate.getTime())) {
        date.innerHTML = `<strong>${escapeHtml(new Intl.DateTimeFormat(lang === "ru" ? "ru-RU" : lang === "en" ? "en-GB" : "uz-UZ", { day: "2-digit", timeZone: "Asia/Tashkent" }).format(eventDate))}</strong><small>${escapeHtml(new Intl.DateTimeFormat(lang === "ru" ? "ru-RU" : lang === "en" ? "en-GB" : "uz-UZ", { month: "short", timeZone: "Asia/Tashkent" }).format(eventDate))}</small>`;
      } else date.textContent = formatCalendarDate(item.starts_at);
      const copy = document.createElement("div");
      copy.className = "calendar-event-copy";
      const title = document.createElement("h4");
      title.textContent = String(item.title || "");
      const description = document.createElement("p");
      description.textContent = String(item.description || "");
      const meta = document.createElement("div");
      meta.className = "calendar-event-meta";
      meta.textContent =
        formatCalendarDate(item.starts_at) +
        (item.location ? ` · ${String(item.location)}` : "");
      copy.append(title);
      if (description.textContent) copy.append(description);
      copy.append(meta);
      article.append(date, copy);
      root.append(article);
    }
  } catch (_error) {
    // Public timetable remains usable while the API/calendar is unavailable.
    panel.hidden = true;
  }
}

