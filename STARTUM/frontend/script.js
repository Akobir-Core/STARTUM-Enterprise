/* STARTUM signature opening — 6.2s, once per tab session; ?intro=preview forces a replay. */
function setupCinematicIntro() {
  const intro = $("#startumOpening");
  if (!intro) return;

  const params = new URLSearchParams(window.location.search);
  const forcePreview = params.get("intro") === "preview";
  const reducedMotion = window.matchMedia?.(
    "(prefers-reduced-motion: reduce)",
  ).matches;
  let alreadySeen = false;
  try {
    alreadySeen = sessionStorage.getItem("startumOpeningV2Seen") === "1";
  } catch (_storageError) {}

  // Explicit preview URLs are available for design review even after the intro was seen.
  if ((!forcePreview && alreadySeen) || (reducedMotion && !forcePreview)) {
    intro.hidden = true;
    intro.setAttribute("aria-hidden", "true");
    return;
  }

  const pageRegions = [$(".topbar"), $("#main-content"), $(".footer")].filter(
    Boolean,
  );
  const previousInert = pageRegions.map((node) => node.inert === true);
  pageRegions.forEach((node) => {
    node.inert = true;
  });

  intro.hidden = false;
  intro.setAttribute("aria-hidden", "false");
  intro.classList.remove("is-leaving");
  // Restart CSS timeline reliably when the intro is force-previewed.
  void intro.offsetWidth;
  intro.classList.add("is-active");
  document.body.classList.add("opening-active");

  const skip = $("#skipOpening");
  try {
    skip?.focus({ preventScroll: true });
  } catch (_focusError) {
    skip?.focus();
  }

  let closed = false;
  let autoTimer = 0;
  let fallbackTimer = 0;
  const skipOnEscape = (event) => {
    if (!closed && event.key === "Escape") finish();
  };
  const finish = () => {
    if (closed) return;
    closed = true;
    window.clearTimeout(autoTimer);
    window.clearTimeout(fallbackTimer);
    document.removeEventListener("keydown", skipOnEscape);
    if (!forcePreview) {
      try {
        sessionStorage.setItem("startumOpeningV2Seen", "1");
      } catch (_storageError) {}
    }
    intro.classList.add("is-leaving");
    window.setTimeout(() => {
      intro.classList.remove("is-active", "is-leaving");
      intro.hidden = true;
      intro.setAttribute("aria-hidden", "true");
      document.body.classList.remove("opening-active");
      pageRegions.forEach((node, index) => {
        node.inert = previousInert[index];
      });
    }, 760);
  };

  autoTimer = window.setTimeout(finish, 6200);
  fallbackTimer = window.setTimeout(finish, 7600);
  skip?.addEventListener("click", finish, { once: true });
  document.addEventListener("keydown", skipOnEscape);
  const motionPreference = window.matchMedia?.(
    "(prefers-reduced-motion: reduce)",
  );
  motionPreference?.addEventListener?.(
    "change",
    (event) => {
      if (event.matches && !forcePreview) finish();
    },
    { once: true },
  );
}

